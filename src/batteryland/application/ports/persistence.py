from collections.abc import Callable
from contextlib import AbstractContextManager
from typing import Any, Protocol

from batteryland.domain.documents import DocumentRef

type Record = dict[str, Any]


class ResourceRepository(Protocol):
    def add_source(self, name: str, root_alias: str, availability: str) -> Record: ...
    def get_source(self, identity: str) -> Record: ...
    def list_sources(self, page: int, page_size: int) -> Record: ...
    def find_battery(self, source_id: str, file_name: str) -> Record | None: ...
    def get_battery(self, identity: str) -> Record: ...
    def get_batteries(self, identities: list[str]) -> list[Record]: ...
    def add_battery(self, value: Record) -> Record: ...
    def list_batteries(self, filters: Record, page: int, page_size: int) -> Record: ...


class DocumentRepository(Protocol):
    def publish(
        self,
        kind: str,
        owner_id: str,
        version: int,
        payload: Record,
        *,
        document_id: str | None = None,
    ) -> DocumentRef: ...
    def add(self, reference: DocumentRef) -> None: ...
    def read(self, reference: DocumentRef) -> Record: ...
    def import_legacy(self, reference: DocumentRef, envelope: Record) -> None: ...
    def ensure_complete(self) -> None: ...
    def get(self, identity: str) -> DocumentRef: ...
    def find(self, kind: str, owner_id: str, version: int) -> DocumentRef: ...
    def storage_keys(self) -> set[str]: ...


class UnitOfWork(Protocol):
    @property
    def resources(self) -> ResourceRepository: ...
    @property
    def documents(self) -> DocumentRepository: ...

    @property
    def splits(self) -> SplitRepository: ...

    @property
    def templates(self) -> TemplateRepository: ...

    @property
    def experiments(self) -> ExperimentRepository: ...

    @property
    def artifacts(self) -> ArtifactRepository: ...

    @property
    def results(self) -> ResultRepository: ...


class SplitRepository(Protocol):
    def add(self, identity: str, name: str, source_id: str, document_id: str) -> Record: ...
    def get(self, identity: str) -> Record: ...
    def update(self, identity: str, revision: int, name: str, document_id: str) -> Record: ...
    def add_members(self, document_id: str, partitions: dict[str, list[str]]) -> None: ...
    def list_splits(
        self, source_id: str | None, q: str | None, page: int, page_size: int
    ) -> Record: ...
    def members(
        self, document_id: str, partition: str | None, page: int, page_size: int
    ) -> Record: ...
    def delete(self, identity: str) -> None: ...


type UnitOfWorkFactory = Callable[[], AbstractContextManager[UnitOfWork]]


class TemplateRepository(Protocol):
    def add(self, identity: str, name: str, document_id: str) -> Record: ...
    def get(self, identity: str) -> Record: ...
    def update(self, identity: str, revision: int, name: str, document_id: str) -> Record: ...
    def list(self, q: str | None, page: int, page_size: int) -> Record: ...
    def delete(self, identity: str) -> None: ...


class ExperimentRepository(Protocol):
    def add(
        self, identity: str, value: Record, document_id: str, references: Record, query: Record
    ) -> Record: ...
    def get(self, identity: str) -> Record: ...
    def update(
        self,
        identity: str,
        revision: int,
        value: Record,
        document_id: str,
        references: Record,
        query: Record,
    ) -> Record: ...
    def list_experiments(self, filters: Record, page: int, page_size: int) -> Record: ...
    def delete(self, identity: str) -> None: ...
    def enqueue(
        self, identity: str, revision: int, snapshot_id: str, device: str, intent_id: str
    ) -> None: ...
    def executions(self, states: set[str]) -> list[Record]: ...
    def execution(self, identity: str) -> Record: ...
    def transition(
        self, identity: str, expected: set[str], target: str, fields: Record
    ) -> bool: ...
    def update_execution(self, identity: str, fields: Record) -> None: ...


class ArtifactRepository(Protocol):
    def get(self, identity: str) -> Record: ...
    def add(self, value: Record) -> Record: ...
    def sync_components(self, values: list[Record]) -> list[Record]: ...
    def component(self, identity: str) -> Record: ...
    def checkpoints(self, filters: Record, page: int, page_size: int) -> Record: ...
    def for_experiment(self, identity: str) -> list[Record]: ...
    def upsert(self, value: Record) -> Record: ...


class ResultRepository(Protocol):
    def get(self, identity: str) -> Record: ...
    def status(self, identity: str, status: str, error: str | None) -> None: ...
    def publish(
        self, identity: str, document_id: str, artifact_id: str, version: int, metrics: list[Record]
    ) -> None: ...
    def cursor(self, identity: str) -> Record | None: ...
    def ingest(self, identity: str, cursor: Record, metrics: list[Record], reset: bool) -> None: ...
    def metrics(self, identity: str, filters: Record, page: int, page_size: int) -> Record: ...
