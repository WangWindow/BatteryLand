from pathlib import Path
from typing import BinaryIO, Protocol

from batteryland.application.ports.persistence import Record


class SourceFiles(Protocol):
    def options(self) -> list[Record]: ...
    def inspect(self, alias: str, relative_key: str | None = None) -> str: ...
    def list_files(self, alias: str, q: str | None, page: int, page_size: int) -> Record: ...


class ArtifactFiles(Protocol):
    def save(self, stream: BinaryIO, filename: str, limit: int) -> Record: ...
    def resolve(self, relative_key: str) -> Path: ...


class ResultFiles(Protocol):
    def scan(self, directory: str, terminal: bool) -> list[Record]: ...
    def read_result(self, key: str) -> bytes: ...
    def archive(self, identity: str, content: bytes) -> Record: ...
    def metrics_batch(self, key: str, cursor: Record | None) -> Record: ...
    def log_chunk(
        self, identity: str, directory: str | None, stream: str, cursor: str | None, limit: int
    ) -> Record: ...
